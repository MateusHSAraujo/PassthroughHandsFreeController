using System;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Settings hub canvas. The hierarchy lives in the SettingsUI prefab and is referenced through serialized fields;
/// this script only binds events and refreshes values. "Rebuild Layout" (component context menu) regenerates the
/// hierarchy with <see cref="GazeUIFactory"/> and overwrites manual tweaks, so prefer editing the prefab directly.
/// Speed, mesh and control-mode changes are saved immediately through <see cref="SettingsStore"/>.
/// </summary>
[RequireComponent(typeof(LineOfSightPositioner))]
public class SettingsUI : CameraGazeControlledCanvas
{
    public static SettingsUI Instance;

    [Header("Settings UI Appearance:")]
    [Tooltip("RoundedBoxUI material from the Meta Interaction SDK (same as the other canvases). Null = square corners.")]
    public Material RoundedMaterial;
    [Tooltip("Optional click sound played on dwell activation.")]
    public AudioClip ClickClip;
    [Tooltip("Roboto SDF fonts matching the other canvases.")]
    public TMP_FontAsset RegularFont;
    public TMP_FontAsset MediumFont;
    public TMP_FontAsset BoldFont;
    public Vector2 PanelSize = new(340f, 404f);
    public float RowHeight = 32f;

    [Header("Gaze Dwell Settings:")]
    public float OptionDwellTime = 1.15f;
    public float NavigationDwellTime = 1.6f;

    public event Action OnBackRequested;
    public event Action OnServerConfigRequested;

    [Header("Layout References (generated by Rebuild Layout):")]
    [SerializeField] private Button _serverButton;
    [SerializeField] private TextMeshProUGUI _serverSubtitle;
    [SerializeField] private TextMeshProUGUI _linearLabel;
    [SerializeField] private TextMeshProUGUI _angularLabel;
    [SerializeField] private GazeStepper _linearStepper;
    [SerializeField] private GazeStepper _angularStepper;
    [SerializeField] private GazeOptionSelector _meshSelector;
    [SerializeField] private GazeOptionSelector _modeSelector;
    [SerializeField] private TextMeshProUGUI _modeDescription;
    [SerializeField] private Button _backButton;

    private bool HasLayout => _serverButton != null && _linearStepper != null && _angularStepper != null &&
                              _meshSelector != null && _modeSelector != null && _backButton != null;

    protected override void Awake()
    {
        DebugLogger.Log("SettingsUI Awake called.");
        Debug.Assert(Instance == null);
        Instance = this;
        enableSoftFollow = true;
        base.Awake();

        if (!HasLayout)
        {
            DebugLogger.LogWarning("SettingsUI layout references are missing; building layout at runtime. Run Rebuild Layout on the prefab.");
            RebuildLayout();
        }
        BindEvents();
    }

    private void BindEvents()
    {
        _serverButton.onClick.AddListener(() => OnServerConfigRequested?.Invoke());
        _backButton.onClick.AddListener(() => OnBackRequested?.Invoke());

        _linearStepper.ValueChanged += v => SettingsStore.Update(s => s.LinearSpeed = v);
        _angularStepper.ValueChanged += v => SettingsStore.Update(s => s.AngularSpeed = v);
        _meshSelector.OptionSelected += i => SettingsStore.Update(s => s.MeshVisible = i == 0);

        var modes = ControlModeRegistry.All;
        for (int i = 0; i < modes.Count && i < _modeSelector.OptionCount; i++) _modeSelector.SetAvailable(i, modes[i].IsAvailable);
        _modeSelector.OptionSelected += i =>
        {
            if (i < modes.Count) SettingsStore.Update(s => s.ControlMode = modes[i].Id);
            RefreshModeDescription();
        };
    }

    private void OnDestroy()
    {
        if (Instance == this) Instance = null;
        RestThruServer.LimitsUpdated -= OnLimitsUpdated;
    }

    private void OnEnable()
    {
        RestThruServer.LimitsUpdated += OnLimitsUpdated;
    }

    private void OnDisable()
    {
        RestThruServer.LimitsUpdated -= OnLimitsUpdated;
    }

    #region Layout

    /// <summary>
    /// Regenerates the whole hierarchy and its serialized references. Run it on the prefab
    /// (component context menu) when the layout structure changes, e.g. a new control mode.
    /// </summary>
    [ContextMenu("Rebuild Layout")]
    public void RebuildLayout()
    {
        for (int i = transform.childCount - 1; i >= 0; i--)
        {
            GameObject child = transform.GetChild(i).gameObject;
            if (Application.isPlaying) Destroy(child);
            else DestroyImmediate(child);
        }

        GazeUITheme theme = new()
        {
            RoundedMaterial = RoundedMaterial,
            ClickClip = ClickClip,
            RegularFont = RegularFont,
            MediumFont = MediumFont,
            BoldFont = BoldFont
        };

        RectTransform root = GetComponent<RectTransform>();
        root.sizeDelta = PanelSize;

        RectTransform panel = GazeUIFactory.CreateRect("SettingsPanel", transform);
        panel.anchorMin = Vector2.zero;
        panel.anchorMax = Vector2.one;
        panel.offsetMin = Vector2.zero;
        panel.offsetMax = Vector2.zero;

        Image panelImage = panel.gameObject.AddComponent<Image>();
        panelImage.color = theme.PanelColor;
        panelImage.raycastTarget = false;
        GazeUIFactory.ApplyRounded(panelImage, theme, theme.PanelRadius);

        VerticalLayoutGroup vlg = panel.gameObject.AddComponent<VerticalLayoutGroup>();
        vlg.padding = new RectOffset(16, 16, 12, 14);
        vlg.spacing = 4f;
        vlg.childAlignment = TextAnchor.UpperCenter;
        vlg.childControlWidth = true;
        vlg.childControlHeight = true;
        vlg.childForceExpandWidth = true;
        vlg.childForceExpandHeight = false;

        TextMeshProUGUI title = GazeUIFactory.CreateText(panel, "Title", "Settings", 18f, Color.white, TextAlignmentOptions.Center, theme.BoldFont);
        GazeUIFactory.SetLayoutSize(title, preferredHeight: 26f);

        // Server
        AddSectionLabel(panel, "RestThru Server", theme);
        var server = GazeUIFactory.CreateButton(panel, "ServerButton", string.Empty, GazeButtonStyle.Secondary,
            NavigationDwellTime, false, theme, 12f, RowHeight + 4f);
        GazeUIFactory.SetLayoutSize(server.Button, preferredHeight: RowHeight + 4f);
        server.Label.alignment = TextAlignmentOptions.Left;
        server.Label.rectTransform.offsetMin = new Vector2(14f, 2f);
        _serverButton = server.Button;
        _serverSubtitle = server.Label;

        // Linear speed
        _linearLabel = AddSectionLabel(panel, "Linear speed", theme);
        _linearStepper = GazeStepper.Create(panel, "LinearSpeed",
            AppSettings.LinearSpeedMin, AppSettings.LinearSpeedMax, AppSettings.LinearSpeedStep, "mm/s",
            BuildPresets(AppSettings.GetLinearPreset), OptionDwellTime, theme, RowHeight);

        // Angular speed
        _angularLabel = AddSectionLabel(panel, "Rotation speed", theme);
        _angularStepper = GazeStepper.Create(panel, "AngularSpeed",
            AppSettings.AngularSpeedMin, AppSettings.AngularSpeedMax, AppSettings.AngularSpeedStep, string.Empty,
            BuildPresets(AppSettings.GetAngularPreset), OptionDwellTime, theme, RowHeight);

        // Room mesh
        AddSectionLabel(panel, "Room mesh", theme);
        _meshSelector = GazeOptionSelector.Create(panel, "MeshVisibility", new[] { "Visible", "Hidden" },
            OptionDwellTime, theme, RowHeight);

        // Control mode
        AddSectionLabel(panel, "Control mode", theme);
        var modes = ControlModeRegistry.All;
        string[] modeLabels = new string[modes.Count];
        for (int i = 0; i < modes.Count; i++) modeLabels[i] = modes[i].DisplayName;
        _modeSelector = GazeOptionSelector.Create(panel, "ControlMode", modeLabels, OptionDwellTime, theme, RowHeight, 10f);

        _modeDescription = GazeUIFactory.CreateText(panel, "ModeDescription", string.Empty, 9.5f, GazeUIFactory.SubtleTextColor, TextAlignmentOptions.Center, theme.RegularFont);
        GazeUIFactory.SetLayoutSize(_modeDescription, preferredHeight: 14f);

        // Back
        var back = GazeUIFactory.CreateButton(panel, "BackButton", "Back", GazeButtonStyle.Primary,
            NavigationDwellTime, false, theme, 13f, 38f);
        GazeUIFactory.SetLayoutSize(back.Button, preferredHeight: 38f);
        _backButton = back.Button;

        // Match the overlay layer used by the other canvases
        int layer = gameObject.layer;
        foreach (Transform t in GetComponentsInChildren<Transform>(true)) t.gameObject.layer = layer;
    }

    private static (string, float)[] BuildPresets(Func<SpeedPreset, float> getter)
    {
        return new[]
        {
            ("Slow", getter(SpeedPreset.Slow)),
            ("Normal", getter(SpeedPreset.Normal)),
            ("Fast", getter(SpeedPreset.Fast)),
        };
    }

    private static TextMeshProUGUI AddSectionLabel(Transform parent, string text, GazeUITheme theme)
    {
        TextMeshProUGUI label = GazeUIFactory.CreateText(parent, $"Label_{text}", text, 10.5f, GazeUIFactory.SubtleTextColor,
            TextAlignmentOptions.Left, theme.RegularFont);
        GazeUIFactory.SetLayoutSize(label, preferredHeight: 14f);
        return label;
    }

    #endregion

    #region Show / refresh

    public override void ShowCanvas()
    {
        LoadCurrentValues();
        base.ShowCanvas();
    }

    public override void ShowCanvasAtDirectionOf(Vector3 targetPosition)
    {
        LoadCurrentValues();
        base.ShowCanvasAtDirectionOf(targetPosition);
    }

    private void LoadCurrentValues()
    {
        AppSettings settings = SettingsStore.Current;

        if (_serverSubtitle != null) _serverSubtitle.text = $"{RestThruServer.BaseUrl}  <size=80%>(edit)</size>";

        _linearStepper.SetValue(settings.LinearSpeed, false);
        _angularStepper.SetValue(settings.AngularSpeed, false);
        _meshSelector.Select(settings.MeshVisible ? 0 : 1, false);

        IControlMode active = ControlModeRegistry.Active;
        var modes = ControlModeRegistry.All;
        for (int i = 0; i < modes.Count && i < _modeSelector.OptionCount; i++)
        {
            if (modes[i].Id == active.Id) _modeSelector.Select(i, false);
        }
        RefreshModeDescription();
        OnLimitsUpdated(RestThruServer.ServerMaxWheelSpeed);
    }

    private void RefreshModeDescription()
    {
        if (_modeDescription == null) return;
        _modeDescription.text = ControlModeRegistry.Active.Description;
    }

    private void OnLimitsUpdated(float? serverMax)
    {
        if (_linearStepper == null) return;
        string suffix = serverMax.HasValue ? $"  <size=85%>(server max {serverMax.Value:0})</size>" : string.Empty;
        _linearLabel.text = "Linear speed" + suffix;
        _angularLabel.text = "Rotation speed" + suffix;
    }

    #endregion
}
