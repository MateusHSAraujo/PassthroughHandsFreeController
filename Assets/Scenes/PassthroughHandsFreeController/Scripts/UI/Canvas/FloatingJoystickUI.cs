using TMPro;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Hands-free gaze pad anchored to the wheelchair (see <see cref="ChairAnchoredPositioner"/>).
/// Four ring wedges (Forward, Back, Turn left, Turn right) around a central rest zone. Wedges are NOT dwell
/// buttons: the gaze arms a wedge after a short delay and the chair moves while the gaze stays on it; it stops as
/// soon as the gaze leaves. Zone detection is geometric (head ray vs. pad plane) through <see cref="GazePadZoneTracker"/>.
/// The hierarchy lives in the FloatingJoystickUI prefab ("Rebuild Layout" regenerates it with <see cref="GazeUIFactory"/>).
/// </summary>
[RequireComponent(typeof(ChairAnchoredPositioner))]
public class FloatingJoystickUI : CameraGazeControlledCanvas, ITeleopInput, ITeleopLinkListener
{
    public static FloatingJoystickUI Instance;

    // Order of the wedge arrays below.
    private static readonly PadDirection[] WedgeOrder =
    {
        PadDirection.Forward, PadDirection.TurnLeft, PadDirection.Back, PadDirection.TurnRight
    };

    [Header("Floating Joystick Appearance:")]
    [Tooltip("RoundedBoxUI material from the Meta Interaction SDK (same as the other canvases). Null = square corners.")]
    public Material RoundedMaterial;
    [Tooltip("Played when motion starts and stops.")]
    public AudioClip ClickClip;
    public TMP_FontAsset RegularFont;
    public TMP_FontAsset MediumFont;
    public TMP_FontAsset BoldFont;
    [Range(0f, 1f)] public float DiscAlpha = 0.55f;

    [Header("Gaze Pad:")]
    public GazePadGeometry Geometry = new();

    [Header("Layout References (generated by Rebuild Layout):")]
    [SerializeField] private Image _disc;
    [SerializeField] private RingSegmentGraphic[] _wedges = new RingSegmentGraphic[4];
    [SerializeField] private Graphic[] _wedgeIcons = new Graphic[0];
    [SerializeField] private TextMeshProUGUI[] _wedgeLabels = new TextMeshProUGUI[4];
    [SerializeField] private TextMeshProUGUI _status;

    // Palette shared with ToggleGazeInteractor presets.
    private static readonly Color IdleColor = new(1f, 1f, 1f, 0.10f);
    private static readonly Color ArmingColor = new(0f, 0.39f, 0.88f, 0.85f);
    private static readonly Color ActiveColor = new(0.18f, 0.58f, 1f, 1f);
    private static readonly Color IconColor = Color.white;
    private static readonly Color IconDimColor = new(1f, 1f, 1f, 0.35f);

    private GazePadZoneTracker _tracker;
    private AudioSource _audio;
    private bool _exitRequested;
    private bool _linkFault;
    private PadDirection _lastActive = PadDirection.None;

    private bool HasLayout => _disc != null && _status != null && _wedges != null && _wedges.Length == 4 &&
                              System.Array.TrueForAll(_wedges, w => w != null);

    /// <summary>Direction currently driving the chair (None when stopped).</summary>
    public PadDirection ActiveDirection => _tracker != null ? _tracker.Active : PadDirection.None;

    protected override void Awake()
    {
        DebugLogger.Log("FloatingJoystickUI Awake called.");
        Debug.Assert(Instance == null);
        Instance = this;
        enableSoftFollow = false;
        base.Awake();

        _audio = GetComponent<AudioSource>();
        _tracker = new GazePadZoneTracker(Geometry);

        if (!HasLayout)
        {
            DebugLogger.LogWarning("FloatingJoystickUI layout references are missing; building layout at runtime. Run Rebuild Layout on the prefab.");
            RebuildLayout();
        }
    }

    private void OnDestroy()
    {
        if (Instance == this) Instance = null;
    }

    public override void Update()
    {
        base.Update();
        if (_tracker == null) return;

        if (!IsVisible)
        {
            if (_lastActive != PadDirection.None) _tracker.Reset();
            _lastActive = PadDirection.None;
            return;
        }

        bool trackingOk = OVRManager.tracker != null && OVRManager.tracker.isPositionTracked &&
                          OVRInput.GetControllerPositionTracked(OVRInput.Controller.LTouch) &&
                          OVRInput.GetControllerPositionTracked(OVRInput.Controller.RTouch);

        bool hasHit = TryGetGazePoint(out Vector2 localPoint);
        _tracker.Update(hasHit, localPoint, IsInputUnlocked && !_exitRequested && !_linkFault, trackingOk, Time.unscaledTime);

        if (_tracker.Active != _lastActive)
        {
            DebugLogger.Log($"FloatingJoystick: {_lastActive} -> {_tracker.Active} (status={_tracker.Status})");
            if (_audio != null && ClickClip != null) _audio.PlayOneShot(ClickClip);
            _lastActive = _tracker.Active;
        }

        RefreshVisuals();
    }

    private bool TryGetGazePoint(out Vector2 localPoint)
    {
        localPoint = Vector2.zero;
        Transform head = OVRUtils.CenterEyeAnchor;
        if (head == null) return false;

        Plane plane = new(transform.forward, transform.position);
        Ray ray = new(head.position, head.forward);
        if (!plane.Raycast(ray, out float enter)) return false;

        Vector3 local = transform.InverseTransformPoint(ray.GetPoint(enter));
        localPoint = new Vector2(local.x, local.y);
        return true;
    }

    #region ITeleopInput
    public TeleopCommand Current
    {
        get
        {
            if (!IsVisible || _exitRequested || _linkFault || _tracker == null) return TeleopCommand.Zero;
            return _tracker.Active switch
            {
                PadDirection.Forward => new TeleopCommand(1f, 0f),
                PadDirection.Back => new TeleopCommand(-1f, 0f),
                PadDirection.TurnLeft => new TeleopCommand(0f, 1f),   // CCW
                PadDirection.TurnRight => new TeleopCommand(0f, -1f), // CW
                _ => TeleopCommand.Zero
            };
        }
    }

    public bool ExitRequested => _exitRequested;

    public void OnTeleopStarted()
    {
        _exitRequested = false;
        _linkFault = false;
    }

    public void OnTeleopEnded() { }

    // The loop could not reach the robot (request failed / timed out) and is trying to stop it. Drop the active wedge so
    // the gaze has to go through the centre again once the link is back.
    public void OnTeleopLinkFault()
    {
        _linkFault = true;
        _tracker?.Reset();
        _lastActive = PadDirection.None;
    }

    public void OnTeleopLinkRecovered() => _linkFault = false;

    /// <summary>Asks the streaming loop to stop the chair and end. The command is zero from now on.</summary>
    public void RequestExit() => _exitRequested = true;
    #endregion

    public override void ShowCanvas()
    {
        _tracker?.Reset();
        _lastActive = PadDirection.None;
        _exitRequested = false;
        base.ShowCanvas();
        RefreshVisuals();
    }

    public override void HideCanvas()
    {
        _tracker?.Reset();
        _lastActive = PadDirection.None;
        base.HideCanvas();
    }

    private void RefreshVisuals()
    {
        if (!HasLayout || _tracker == null) return;

        PadStatus status = _tracker.Status;
        bool blocked = _linkFault || status == PadStatus.Locked || status == PadStatus.TrackingLost;
        bool waiting = status == PadStatus.NeedsCenter;

        for (int i = 0; i < WedgeOrder.Length; i++)
        {
            PadDirection dir = WedgeOrder[i];
            Color c;
            if (blocked) c = GazeUIFactory.DisabledColor;
            else if (_tracker.Active == dir) c = ActiveColor;
            else if (_tracker.Candidate == dir) c = Color.Lerp(IdleColor, ArmingColor, _tracker.ArmProgress);
            else c = IdleColor;
            _wedges[i].color = c;

            Color iconColor = blocked || waiting ? IconDimColor : IconColor;
            if (i < _wedgeLabels.Length && _wedgeLabels[i] != null) _wedgeLabels[i].color = iconColor;
        }
        if (_wedgeIcons != null)
        {
            Color iconColor = blocked || waiting ? IconDimColor : IconColor;
            foreach (Graphic icon in _wedgeIcons) if (icon != null) icon.color = iconColor;
        }

        _status.text = _linkFault ? "No link. Stopping..." : GazePadZoneTracker.Describe(status, _tracker.Active);
    }

    #region Layout
    /// <summary>Regenerates the pad hierarchy and its serialized references. Overwrites manual tweaks.</summary>
    [ContextMenu("Rebuild Layout")]
    public void RebuildLayout()
    {
        for (int i = transform.childCount - 1; i >= 0; i--)
        {
            GameObject child = transform.GetChild(i).gameObject;
            if (Application.isPlaying) Destroy(child);
            else DestroyImmediate(child);
        }

        GazeUITheme theme = new()
        {
            RoundedMaterial = RoundedMaterial,
            ClickClip = ClickClip,
            RegularFont = RegularFont,
            MediumFont = MediumFont,
            BoldFont = BoldFont
        };

        float outer = Geometry.outerRadius;
        float inner = Geometry.innerRadius;
        float diameter = outer * 2f + 16f;

        RectTransform root = GetComponent<RectTransform>();
        root.pivot = new Vector2(0.5f, 0.5f);
        root.sizeDelta = new Vector2(diameter, diameter);

        // Disc background: raycast target so the existing gaze cursor shows on the pad.
        RectTransform discRt = CreateCentered("Disc", transform, new Vector2(diameter, diameter), Vector2.zero);
        _disc = discRt.gameObject.AddComponent<Image>();
        Color discColor = theme.PanelColor;
        discColor.a = DiscAlpha;
        _disc.color = discColor;
        _disc.raycastTarget = true;
        GazeUIFactory.ApplyRounded(_disc, theme, diameter * 0.5f);

        _wedges = new RingSegmentGraphic[4];
        _wedgeLabels = new TextMeshProUGUI[4];
        var icons = new System.Collections.Generic.List<Graphic>();
        string[] labels = { "Forward", "Turn left", "Back", "Turn right" };
        float iconRadius = inner + (outer - inner) * 0.36f;
        float labelRadius = inner + (outer - inner) * 0.74f;

        for (int i = 0; i < WedgeOrder.Length; i++)
        {
            PadDirection dir = WedgeOrder[i];
            float angle = GazePadZoneTracker.CenterAngle(dir);

            RectTransform wedgeRt = CreateCentered($"Wedge_{dir}", discRt, new Vector2(diameter, diameter), Vector2.zero);
            RingSegmentGraphic wedge = wedgeRt.gameObject.AddComponent<RingSegmentGraphic>();
            wedge.innerRadius = inner;
            wedge.outerRadius = outer;
            wedge.centerAngleDeg = angle;
            wedge.sweepDeg = Geometry.HalfWidthDeg * 2f;
            wedge.raycastTarget = false;
            wedge.color = IdleColor;
            _wedges[i] = wedge;

            bool isSide = dir == PadDirection.TurnLeft || dir == PadDirection.TurnRight;
            // Side wedges are short horizontally: icon on top, label right below it (both inside the wedge).
            Vector2 sideCenter = Polar(inner + (outer - inner) * 0.52f, angle);
            Vector2 iconPos = isSide ? sideCenter + new Vector2(0f, 10f) : Polar(iconRadius, angle);
            if (dir == PadDirection.Forward || dir == PadDirection.Back)
            {
                RectTransform tri = CreateCentered($"Icon_{dir}", discRt, new Vector2(28f, 20f), iconPos);
                tri.localRotation = Quaternion.Euler(0f, 0f, angle - 90f); // points outward
                TriangleGraphic g = tri.gameObject.AddComponent<TriangleGraphic>();
                g.raycastTarget = false;
                icons.Add(g);
            }
            else
            {
                icons.AddRange(CreateCurvedArrow(discRt, $"Icon_{dir}", iconPos, dir == PadDirection.TurnLeft));
            }

            TextMeshProUGUI label = GazeUIFactory.CreateText(discRt, $"Label_{dir}", labels[i], 10f, GazeUIFactory.LabelColor,
                TextAlignmentOptions.Center, theme.MediumFont);
            RectTransform labelRt = label.rectTransform;
            labelRt.anchorMin = labelRt.anchorMax = new Vector2(0.5f, 0.5f);
            labelRt.sizeDelta = new Vector2(64f, 16f);
            labelRt.anchoredPosition = isSide ? sideCenter + new Vector2(0f, -20f) : Polar(labelRadius, angle);
            _wedgeLabels[i] = label;
        }
        _wedgeIcons = icons.ToArray();

        // Center rest zone with status text.
        float centerSize = (inner - 4f) * 2f;
        RectTransform centerRt = CreateCentered("Center", discRt, new Vector2(centerSize, centerSize), Vector2.zero);
        Image center = centerRt.gameObject.AddComponent<Image>();
        center.color = new Color(1f, 1f, 1f, 0.06f);
        center.raycastTarget = false;
        GazeUIFactory.ApplyRounded(center, theme, centerSize * 0.5f);

        _status = GazeUIFactory.CreateText(centerRt, "Status", string.Empty, 8.5f, GazeUIFactory.SubtleTextColor,
            TextAlignmentOptions.Center, theme.RegularFont);
        _status.textWrappingMode = TextWrappingModes.Normal;
        RectTransform statusRt = _status.rectTransform;
        statusRt.anchorMin = Vector2.zero;
        statusRt.anchorMax = Vector2.one;
        statusRt.offsetMin = new Vector2(6f, 6f);
        statusRt.offsetMax = new Vector2(-6f, -6f);
    }

    /// <summary>Curved arrow (arc + head): counter-clockwise for turn left, clockwise for turn right.</summary>
    private static Graphic[] CreateCurvedArrow(Transform parent, string name, Vector2 position, bool counterClockwise)
    {
        const float arcInner = 10f, arcOuter = 14f, arcSweep = 230f;
        RectTransform container = CreateCentered(name, parent, new Vector2(36f, 36f), position);

        RectTransform arcRt = CreateCentered("Arc", container, new Vector2(36f, 36f), Vector2.zero);
        RingSegmentGraphic arc = arcRt.gameObject.AddComponent<RingSegmentGraphic>();
        arc.innerRadius = arcInner;
        arc.outerRadius = arcOuter;
        arc.centerAngleDeg = 90f;
        arc.sweepDeg = arcSweep;
        arc.segments = 24;
        arc.raycastTarget = false;

        // The head sits at the arc end the arrow travels toward, oriented along the tangent.
        float endAngle = counterClockwise ? 90f + arcSweep * 0.5f : 90f - arcSweep * 0.5f;
        float mid = (arcInner + arcOuter) * 0.5f;
        RectTransform headRt = CreateCentered("Head", container, new Vector2(13f, 10f), Polar(mid, endAngle));
        headRt.localRotation = Quaternion.Euler(0f, 0f, counterClockwise ? endAngle : endAngle - 180f);
        TriangleGraphic head = headRt.gameObject.AddComponent<TriangleGraphic>();
        head.raycastTarget = false;

        return new Graphic[] { arc, head };
    }

    private static RectTransform CreateCentered(string name, Transform parent, Vector2 size, Vector2 position)
    {
        RectTransform rt = GazeUIFactory.CreateRect(name, parent);
        rt.anchorMin = rt.anchorMax = new Vector2(0.5f, 0.5f);
        rt.pivot = new Vector2(0.5f, 0.5f);
        rt.sizeDelta = size;
        rt.anchoredPosition = position;
        return rt;
    }

    private static Vector2 Polar(float radius, float angleDeg)
    {
        float a = angleDeg * Mathf.Deg2Rad;
        return new Vector2(Mathf.Cos(a), Mathf.Sin(a)) * radius;
    }
    #endregion
}
