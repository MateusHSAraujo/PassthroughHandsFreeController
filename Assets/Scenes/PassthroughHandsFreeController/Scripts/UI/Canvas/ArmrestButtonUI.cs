using System;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// A single gaze-dwell button floating above one armrest controller (see <see cref="ChairAnchoredPositioner"/>,
/// LeftController/RightController mode with billboardToHead). Used by the Floating Joystick mode:
/// left armrest = Menu, right armrest = Minimize / Open pad. Circular, icon-only (no text). Sprites come from one shared
/// <see cref="ArmrestIconSet"/> asset, so adding an icon never changes this class or the prefab.
/// The hierarchy lives in the ArmrestButtonUI prefab ("Rebuild Layout" regenerates it with <see cref="GazeUIFactory"/>).
/// </summary>
[RequireComponent(typeof(ChairAnchoredPositioner))]
public class ArmrestButtonUI : CameraGazeControlledCanvas
{
    [Header("Armrest Button Appearance:")]
    public Material RoundedMaterial;
    public AudioClip ClickClip;
    public TMP_FontAsset RegularFont;
    public TMP_FontAsset MediumFont;
    public TMP_FontAsset BoldFont;
    public float ButtonDiameter = 64f;
    public float IconSize = 32f;

    [Header("Icons:")]
    [Tooltip("Shared asset that maps every ArmrestIcon to a sprite. Edit the sprites there.")]
    public ArmrestIconSet Icons;
    [Tooltip("Icon shown when the scene loads (the state changes it at runtime). Left armrest = Menu, right armrest = Minimize.")]
    public ArmrestIcon DefaultIcon = ArmrestIcon.Menu;

    [Header("Gaze Dwell Settings:")]
    public float NavigationDwellTime = 1.6f;

    [Header("Layout References (generated by Rebuild Layout):")]
    [SerializeField] private Button _button;
    [SerializeField] private Image _icon;

    public event Action OnActivated;

    private bool HasLayout => _button != null && _icon != null;

    protected override void Awake()
    {
        enableSoftFollow = false;
        base.Awake();

        if (!HasLayout)
        {
            DebugLogger.LogWarning($"{name}: ArmrestButtonUI layout references are missing; building layout at runtime. Run Rebuild Layout on the prefab.");
            RebuildLayout();
        }
        SetIcon(DefaultIcon);
        _button.onClick.AddListener(() => OnActivated?.Invoke());
    }

    /// <summary>Changes the icon without hiding the canvas, so the dwell interactor keeps its triggered-until-exit guard.</summary>
    public void SetIcon(ArmrestIcon icon)
    {
        if (_icon == null) return;
        Sprite sprite = Icons != null ? Icons.Get(icon) : null;
        _icon.sprite = sprite;
        _icon.enabled = sprite != null;
    }

    [ContextMenu("Rebuild Layout")]
    public void RebuildLayout()
    {
        for (int i = transform.childCount - 1; i >= 0; i--)
        {
            GameObject child = transform.GetChild(i).gameObject;
            if (Application.isPlaying) Destroy(child);
            else DestroyImmediate(child);
        }

        GazeUITheme theme = new()
        {
            RoundedMaterial = RoundedMaterial,
            ClickClip = ClickClip,
            RegularFont = RegularFont,
            MediumFont = MediumFont,
            BoldFont = BoldFont
        };

        Vector2 size = new(ButtonDiameter, ButtonDiameter);
        float radius = ButtonDiameter * 0.5f;
        RectTransform root = GetComponent<RectTransform>();
        root.pivot = new Vector2(0.5f, 0.5f);
        root.sizeDelta = size;

        // Backing disc so the button reads well against passthrough.
        RectTransform panel = GazeUIFactory.CreateRect("Panel", transform);
        panel.anchorMin = Vector2.zero;
        panel.anchorMax = Vector2.one;
        panel.offsetMin = Vector2.zero;
        panel.offsetMax = Vector2.zero;
        Image panelImage = panel.gameObject.AddComponent<Image>();
        panelImage.color = theme.PanelColor;
        panelImage.raycastTarget = false;
        GazeUIFactory.ApplyRounded(panelImage, theme, radius);

        var parts = GazeUIFactory.CreateButton(panel, "Button", string.Empty, GazeButtonStyle.Secondary,
            NavigationDwellTime, false, theme, 12f, ButtonDiameter - 6f);
        RectTransform buttonRt = (RectTransform)parts.Button.transform;
        buttonRt.anchorMin = Vector2.zero;
        buttonRt.anchorMax = Vector2.one;
        buttonRt.offsetMin = new Vector2(3f, 3f);
        buttonRt.offsetMax = new Vector2(-3f, -3f);
        GazeUIFactory.ApplyRounded(parts.Background, theme, radius - 3f); // circle, not a pill
        if (parts.Label != null) DestroyChild(parts.Label.gameObject);

        _button = parts.Button;

        _icon = CreateIcon(buttonRt, "Icon");

        SetIcon(DefaultIcon);
    }

#if UNITY_EDITOR
    // Keeps the scene view in sync with Icons / DefaultIcon while editing.
    private void OnValidate()
    {
        if (!HasLayout) return;
        SetIcon(DefaultIcon);
    }
#endif

    private static void DestroyChild(GameObject go)
    {
        if (Application.isPlaying) Destroy(go);
        else DestroyImmediate(go);
    }

    private static void CenterWithSize(RectTransform rt, Vector2 size)
    {
        rt.anchorMin = rt.anchorMax = new Vector2(0.5f, 0.5f);
        rt.pivot = new Vector2(0.5f, 0.5f);
        rt.anchoredPosition = Vector2.zero;
        rt.sizeDelta = size;
    }

    private Image CreateIcon(RectTransform parent, string name)
    {
        RectTransform rt = GazeUIFactory.CreateRect(name, parent);
        CenterWithSize(rt, new Vector2(IconSize, IconSize));
        Image image = rt.gameObject.AddComponent<Image>();
        image.preserveAspect = true;
        image.color = GazeUIFactory.LabelColor;
        image.raycastTarget = false;
        return image;
    }
}
